// Настройки табло. Токенов ролей здесь нет: с ядром роли и токены отдаёт GET /v1/demo/roles (режим dev),
// в режиме strict человек вводит свой токен; без ядра демо берёт роли из demo/roles.json (js/roles.js).

// Роль по умолчанию — инженер ОТК: он ставит клеймо на защите
export const DEFAULT_ROLE = 'controller';

// Сколько ждать ядро перед переходом в демо
export const CORE_TIMEOUT_MS = 2000;

// Сколько ждать снимок линии, когда ядро уже ответило: на стенде, который крутится час, в снимке сотни деталей,
// и под нагрузкой ответ идёт 3–9 с — табло ждёт, а не пишет «нет связи»
export const LINE_TIMEOUT_MS = 10000;

// Сколько строк полосы «Требует действия» видно без раскрытия — по высоте окна (attn.js берёт больше, если
// помещается, но не больше 7): 1280×720, 1366×768 и 1920×1080 — от 5 строк
// Опрос оповещений, пока у строк полосы есть неподтверждённые: эскалацию ядро делает по своим часам
// (задача раз в 15 с), «Принял» может прийти с другого рабочего места — событий потока для этого нет
export const NOTES_POLL_MS = 30000;

// К38 (QA В-13): строка теперь в две строки текста, около 56 px — на 1280×720 и 1366×768 помещается 5
export function attentionRows(height) {
  if (height >= 640) return 5;
  return height >= 520 ? 3 : 2;
}

// Пост ОТК в узком окне (до 1100 px, как в css/item.css): очередь и профиль друг под другом — после выбора
// детали экран прокручивается к её профилю, иначе он открывается под длинным списком и его не видно
export const OTK_STACK_MAX = 1100;

export function otkStacked(width) {
  return Number(width) > 0 && Number(width) <= OTK_STACK_MAX;
}
